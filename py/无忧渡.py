def parse_raw(text):
    groups = []
    current = None
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        if '#genre#' in line:
            gname = line.split(',')[-1].strip() if ',' in line else line.replace('#genre#', '').strip()
            if not gname:
                gname = '直播'
            current = {'name': gname, 'channels': []}
            groups.append(current)
            continue
        if ',' in line:
            name, url = line.split(',', 1)
            name, url = name.strip(), url.strip()
            if name and url:
                if current is None:
                    current = {'name': '直播', 'channels': []}
                    groups.append(current)
                current['channels'].append({'name': name, 'url': url})
    return groups


